#!/usr/bin/env node
// Writes public/plugin-runtime/*.js: one small module per module the web
// app shares with plugins' web entries. Each re-exports, under
// the module's own export names, what the web app put on
// `globalThis.__ahabShared` before loading plugins; a plugin's build points
// its imports of `react`, `zod`, `@ahab/plugin/web`… at these files.
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../public/plugin-runtime/", import.meta.url));

/** Each shared module and the file it is served as (as the SDK's build names them). */
const SHARED = {
	react: "react",
	"react/jsx-runtime": "react-jsx-runtime",
	"react-dom": "react-dom",
	"react-dom/client": "react-dom-client",
	zod: "zod",
	"@ahab/plugin/shared": "ahab-plugin-shared",
	"@ahab/plugin/web": "ahab-plugin-web",
};

const identifier = /^[A-Za-z_$][\w$]*$/;

await mkdir(out, { recursive: true });
for (const [name, file] of Object.entries(SHARED)) {
	const module = await import(name);
	const names =
		name === "@ahab/plugin/web"
			? [...module.WEB_EXPORTS]
			: Object.keys(module).filter((key) => key !== "default" && identifier.test(key));
	const lines = [
		`// Generated by scripts/plugin-runtime.mjs: Ahab's ${name}, for plugins.`,
		`const shared = globalThis.__ahabShared?.[${JSON.stringify(name)}];`,
		`if (!shared) throw new Error(${JSON.stringify(`Ahab does not share ${name} here.`)});`,
		"export default shared.default ?? shared;",
	];
	if (names.length) lines.push(`export const { ${names.join(", ")} } = shared;`);
	await writeFile(`${out}${file}.js`, `${lines.join("\n")}\n`);
}
console.log(`plugin runtime: ${Object.keys(SHARED).length} modules`);
